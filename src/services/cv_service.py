"""
CV Service
==========
Business logic for CV management and AI-powered generation.
"""

import logging
import json
from typing import Optional, Dict, Any, List
from sqlalchemy.exc import SQLAlchemyError
from src.models.base import db
from src.models.cv import CV
from src.models.job import JobOffer
from src.models.user import User
from src.services.profile_service import ProfileService
from src.services.ai_service import get_ai_service

logger = logging.getLogger(__name__)


class CVService:
    """Service for managing CVs and generating them with AI."""

    # CV Content JSON Schema for validation
    CONTENT_SCHEMA = {
        "required_keys": ["personal", "summary", "experience", "education", "skills"],
        "optional_keys": ["sections"],
    }

    # ===== CRUD Operations =====

    @staticmethod
    def get_cv(
        cv_id: int, user_id: int, include_content: bool = True
    ) -> Optional[Dict[str, Any]]:
        """
        Get a specific CV by ID.

        Args:
            cv_id: CV ID
            user_id: User ID for ownership verification
            include_content: Whether to include full CV content

        Returns:
            CV dictionary or None if not found/not owned
        """
        try:
            cv = db.session.query(CV).filter_by(id=cv_id, user_id=user_id).first()

            if not cv:
                logger.warning(f"CV {cv_id} not found or not owned by user {user_id}")
                return None

            return cv.to_dict(include_content=include_content, include_job=True)

        except SQLAlchemyError as e:
            logger.error(f"Database error getting CV {cv_id}: {str(e)}")
            raise

    @staticmethod
    def get_user_cvs(
        user_id: int, include_content: bool = False, limit: int = 50, offset: int = 0
    ) -> Dict[str, Any]:
        """
        Get all CVs for a user.

        Args:
            user_id: User ID
            include_content: Whether to include full CV content
            limit: Maximum number of results
            offset: Pagination offset

        Returns:
            Dictionary with CVs list and total count
        """
        try:
            query = db.session.query(CV).filter_by(user_id=user_id)
            total = query.count()

            cvs = query.order_by(CV.updated_at.desc()).limit(limit).offset(offset).all()

            return {
                "cvs": [
                    cv.to_dict(include_content=include_content, include_job=True)
                    for cv in cvs
                ],
                "total": total,
                "limit": limit,
                "offset": offset,
            }

        except SQLAlchemyError as e:
            logger.error(f"Database error getting CVs for user {user_id}: {str(e)}")
            raise

    @staticmethod
    def create_cv(
        user_id: int,
        title: str,
        content_json: Dict[str, Any],
        target_position: Optional[str] = None,
        job_offer_id: Optional[int] = None,
        is_ai_generated: bool = False,
        generation_prompt: Optional[str] = None,
    ) -> Dict[str, Any]:
        """
        Create a new CV.

        Args:
            user_id: User ID
            title: CV title
            content_json: CV content as dictionary
            target_position: Target position/role
            job_offer_id: Optional job offer ID if tailored
            is_ai_generated: Whether CV was generated by AI
            generation_prompt: Prompt used for AI generation

        Returns:
            Created CV dictionary

        Raises:
            ValueError: If validation fails
        """
        try:
            # Validate user exists
            user = db.session.query(User).filter_by(id=user_id).first()
            if not user:
                raise ValueError(f"User {user_id} not found")

            # Validate title
            if not title or len(title.strip()) == 0:
                raise ValueError("CV title is required")
            if len(title) > 200:
                raise ValueError("CV title must be 200 characters or less")

            # Validate job offer if provided
            if job_offer_id:
                job = db.session.query(JobOffer).filter_by(id=job_offer_id).first()
                if not job:
                    raise ValueError(f"Job offer {job_offer_id} not found")

            # Validate content structure
            CVService._validate_content(content_json)

            # Create CV
            # Try with new schema first, fallback to old schema if columns don't exist
            try:
                cv = CV(
                    user_id=user_id,
                    title=title.strip(),
                    content_json=content_json,
                    target_position=target_position,
                    job_offer_id=job_offer_id,
                    is_ai_generated=is_ai_generated,
                    generation_prompt=generation_prompt,
                )
                db.session.add(cv)
                db.session.commit()
            except SQLAlchemyError as schema_error:
                # Check if it's a missing column error
                if "does not exist" in str(schema_error) and (
                    "job_offer_id" in str(schema_error)
                    or "is_ai_generated" in str(schema_error)
                ):
                    # Rollback and retry with old schema (without new columns)
                    db.session.rollback()
                    logger.warning(
                        f"New CV columns don't exist, using legacy schema for CV creation"
                    )

                    # Create CV with only old schema columns
                    cv = CV(
                        user_id=user_id,
                        title=title.strip(),
                        content_json=content_json,
                        target_position=target_position,
                    )
                    db.session.add(cv)
                    db.session.commit()
                else:
                    # Different error, re-raise
                    raise

            logger.info(f"Created CV {cv.id} for user {user_id}")
            return cv.to_dict(include_content=True, include_job=True)

        except ValueError:
            raise
        except SQLAlchemyError as e:
            db.session.rollback()
            logger.error(f"Database error creating CV for user {user_id}: {str(e)}")
            raise

    @staticmethod
    def update_cv(
        cv_id: int, user_id: int, updates: Dict[str, Any]
    ) -> Optional[Dict[str, Any]]:
        """
        Update a CV.

        Args:
            cv_id: CV ID
            user_id: User ID for ownership verification
            updates: Dictionary of fields to update

        Returns:
            Updated CV dictionary or None if not found

        Raises:
            ValueError: If validation fails
        """
        try:
            cv = db.session.query(CV).filter_by(id=cv_id, user_id=user_id).first()

            if not cv:
                logger.warning(f"CV {cv_id} not found or not owned by user {user_id}")
                return None

            # Update title
            if "title" in updates:
                title = updates["title"]
                if not title or len(title.strip()) == 0:
                    raise ValueError("CV title cannot be empty")
                if len(title) > 200:
                    raise ValueError("CV title must be 200 characters or less")
                cv.title = title.strip()

            # Update target position
            if "target_position" in updates:
                target = updates["target_position"]
                if target and len(target) > 100:
                    raise ValueError("Target position must be 100 characters or less")
                cv.target_position = target

            # Update content
            if "content" in updates:
                content = updates["content"]
                CVService._validate_content(content)
                cv.content_json = content

            db.session.commit()

            logger.info(f"Updated CV {cv_id} for user {user_id}")
            return cv.to_dict(include_content=True, include_job=True)

        except ValueError:
            raise
        except SQLAlchemyError as e:
            db.session.rollback()
            logger.error(f"Database error updating CV {cv_id}: {str(e)}")
            raise

    @staticmethod
    def delete_cv(cv_id: int, user_id: int) -> bool:
        """
        Delete a CV.

        Args:
            cv_id: CV ID
            user_id: User ID for ownership verification

        Returns:
            True if deleted, False if not found
        """
        try:
            cv = db.session.query(CV).filter_by(id=cv_id, user_id=user_id).first()

            if not cv:
                logger.warning(f"CV {cv_id} not found or not owned by user {user_id}")
                return False

            db.session.delete(cv)
            db.session.commit()

            logger.info(f"Deleted CV {cv_id} for user {user_id}")
            return True

        except SQLAlchemyError as e:
            db.session.rollback()
            logger.error(f"Database error deleting CV {cv_id}: {str(e)}")
            raise

    # ===== AI Generation =====

    @staticmethod
    def generate_generic_cv(
        user_id: int, title: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generate a generic CV from user's profile using AI.

        Args:
            user_id: User ID
            title: Optional CV title (defaults to "Professional CV")

        Returns:
            Generated CV dictionary

        Raises:
            ValueError: If profile is incomplete or AI is unavailable
        """
        try:
            # Get user profile with all details
            profile_data = ProfileService.get_profile(user_id, include_details=True)

            if not profile_data:
                raise ValueError(
                    "Profile not found. Please complete your profile first."
                )

            # Check profile completeness
            CVService._check_profile_completeness(profile_data)

            # Get user info
            user = db.session.query(User).filter_by(id=user_id).first()
            if not user:
                raise ValueError("User not found")

            # Generate CV using AI
            from src.ai.agents.cv_agent import CVGenerationAgent

            ai_service = get_ai_service()
            if not ai_service or not ai_service.is_available():
                raise ValueError(
                    "AI service is currently unavailable. Please try again later."
                )

            # Create CV agent
            cv_agent = CVGenerationAgent(ai_service)

            # Build profile context for generation
            profile_context = CVService._build_profile_context(user, profile_data)

            # Generate CV content
            generation_prompt = "Generate a professional CV from the user's profile"
            cv_content = cv_agent.generate_generic_cv(profile_context)

            # Validate generated content
            if not cv_content or not isinstance(cv_content, dict):
                raise ValueError("Failed to generate CV content")

            # Create CV
            cv_title = title or "Professional CV"
            return CVService.create_cv(
                user_id=user_id,
                title=cv_title,
                content_json=cv_content,
                is_ai_generated=True,
                generation_prompt=generation_prompt,
            )

        except ValueError:
            raise
        except Exception as e:
            logger.error(f"Error generating generic CV for user {user_id}: {str(e)}")
            raise ValueError(f"Failed to generate CV: {str(e)}")

    @staticmethod
    def generate_tailored_cv(
        user_id: int, job_offer_id: int, title: Optional[str] = None
    ) -> Dict[str, Any]:
        """
        Generate a CV tailored to a specific job offer.

        Args:
            user_id: User ID
            job_offer_id: Job offer ID to tailor CV for
            title: Optional CV title (defaults to job title)

        Returns:
            Generated CV dictionary

        Raises:
            ValueError: If profile is incomplete, job not found, or AI is unavailable
        """
        try:
            # Get job offer
            job = db.session.query(JobOffer).filter_by(id=job_offer_id).first()
            if not job:
                raise ValueError("Job offer not found")

            # Get user profile with all details
            profile_data = ProfileService.get_profile(user_id, include_details=True)

            if not profile_data:
                raise ValueError(
                    "Profile not found. Please complete your profile first."
                )

            # Check profile completeness
            CVService._check_profile_completeness(profile_data)

            # Get user info
            user = db.session.query(User).filter_by(id=user_id).first()
            if not user:
                raise ValueError("User not found")

            # Generate CV using AI
            from src.ai.agents.cv_agent import CVGenerationAgent

            ai_service = get_ai_service()
            if not ai_service or not ai_service.is_available():
                raise ValueError(
                    "AI service is currently unavailable. Please try again later."
                )

            # Create CV agent
            cv_agent = CVGenerationAgent(ai_service)

            # Build profile context for generation
            profile_context = CVService._build_profile_context(user, profile_data)

            # Build job context
            job_context = {
                "title": job.title,
                "company": job.company,
                "location": job.location,
                "description": job.description,
                "requirements": job.requirements,
                "job_type": job.job_type,
                "salary_range": job.salary_range
                if hasattr(job, "salary_range")
                else None,
            }

            # Generate tailored CV content
            generation_prompt = (
                f"Generate a CV tailored to: {job.title} at {job.company}"
            )
            cv_content = cv_agent.generate_tailored_cv(profile_context, job_context)

            # Validate generated content
            if not cv_content or not isinstance(cv_content, dict):
                raise ValueError("Failed to generate tailored CV content")

            # Create CV
            cv_title = title or f"CV for {job.title} at {job.company}"
            return CVService.create_cv(
                user_id=user_id,
                title=cv_title,
                content_json=cv_content,
                target_position=job.title,
                job_offer_id=job_offer_id,
                is_ai_generated=True,
                generation_prompt=generation_prompt,
            )

        except ValueError:
            raise
        except Exception as e:
            logger.error(
                f"Error generating tailored CV for user {user_id}, job {job_offer_id}: {str(e)}"
            )
            raise ValueError(f"Failed to generate tailored CV: {str(e)}")

    # ===== Helper Methods =====

    @staticmethod
    def _validate_content(content: Dict[str, Any]) -> None:
        """
        Validate CV content structure.

        Args:
            content: CV content dictionary

        Raises:
            ValueError: If content is invalid
        """
        if not content:
            raise ValueError("CV content cannot be empty")

        if not isinstance(content, dict):
            raise ValueError("CV content must be a dictionary")

        # Check required keys (relaxed validation - AI might have variations)
        required = ["personal", "summary"]
        missing = [key for key in required if key not in content]

        if missing:
            raise ValueError(
                f"CV content missing required fields: {', '.join(missing)}"
            )

        # Validate personal info has basic fields
        personal = content.get("personal", {})
        if not personal.get("name"):
            raise ValueError("CV personal info must include name")

    @staticmethod
    def _check_profile_completeness(profile_data: Dict[str, Any]) -> None:
        """
        Check if profile has enough data for CV generation.

        Args:
            profile_data: Profile dictionary with details

        Raises:
            ValueError: If profile is too incomplete
        """
        warnings = []

        # Check for basic info
        if not profile_data.get("summary"):
            warnings.append("Professional summary is empty")

        # Check for work experience
        work_experiences = profile_data.get("work_experiences", [])
        if not work_experiences:
            warnings.append("No work experience listed")

        # Check for education
        education = profile_data.get("education", [])
        if not education:
            warnings.append("No education listed")

        # Check for skills
        skills = profile_data.get("skills", [])
        if len(skills) < 3:
            warnings.append("Please add at least 3 skills")

        # If there are critical missing items, raise error
        if not work_experiences and not education:
            raise ValueError(
                "Your profile needs more information for CV generation. "
                "Please add at least some work experience or education."
            )

    @staticmethod
    def _build_profile_context(
        user: User, profile_data: Dict[str, Any]
    ) -> Dict[str, Any]:
        """
        Build comprehensive profile context for AI CV generation.

        Args:
            user: User model instance
            profile_data: Profile dictionary with details

        Returns:
            Profile context dictionary for AI
        """
        return {
            "personal": {
                "name": user.name,
                "email": user.email,
                "phone": profile_data.get("phone"),
                "location": profile_data.get("location"),
            },
            "summary": profile_data.get("summary"),
            "work_experiences": profile_data.get("work_experiences", []),
            "education": profile_data.get("education", []),
            "skills": profile_data.get("skills", []),
            "certifications": profile_data.get("certifications", []),
            "projects": profile_data.get("projects", []),
            "languages": profile_data.get("languages", []),
            "preferences": profile_data.get("preferences", {}),
        }
